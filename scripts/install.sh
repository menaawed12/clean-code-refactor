#!/usr/bin/env bash
# clean-code-refactor installer (macOS/Linux; bash 3.2+, no jq dependency).
#
# Target tables below are kept in parity with integrations/registry.json;
# scripts/validate-skill.ps1 fails when the two drift apart.
#
# Exit codes:
#   0 = all requested targets installed/updated or intentionally skipped
#   1 = one or more targets failed
#   2 = usage error, missing source, or preflight abort (nothing was written)

