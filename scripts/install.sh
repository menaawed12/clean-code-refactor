root_for() {
  case "$1" in
    project) printf '%s' "$project_root" ;;
    codex-home) printf '%s' "$codex_home" ;;
    home) printf '%s' "$home_root" ;;
    xdg-config) printf '%s' "$xdg_config_root" ;;
    *) return 1 ;;
  esac
}

join_under_root() {
  local root="$1" relative="$2"
  case "$relative" in
    *..*) fail_usage "Registry path must not contain '..': $relative" ;;
  esac
  printf '%s/%s' "${root%/}" "$relative"
}

path_under_root() {
  local prefix="${1%/}/"
  case "$2" in
    "$prefix"*) return 0 ;;
    *) return 1 ;;
  esac
}

first_reparse_between() {
  # Echo the first symlinked component between root and destination, if any.
  local root="${1%/}" dest="$2" rel current seg oldifs
  if ! path_under_root "$root" "$dest"; then
    printf '%s' "$dest"
    return 0
  fi
  rel="${dest#"$root"/}"
  current="$root"
  oldifs="$IFS"
  IFS='/'
  for seg in $rel; do
    current="$current/$seg"
    if [ -L "$current" ]; then
      IFS="$oldifs"
      printf '%s' "$current"
      return 0
    fi
  done
  IFS="$oldifs"
  return 1
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  elif command -v openssl >/dev/null 2>&1; then
    openssl dgst -sha256 -r "$1" | cut -d' ' -f1
  else
    printf ''
  fi
}

json_escape() {
  local s="$1"
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '%s' "$s"
}

